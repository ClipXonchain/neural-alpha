#!/usr/bin/env bash
set -euo pipefail

# Neural Alpha — production deploy for neuralalpha.io
#
# PM2 apps (only these; never `pm2 restart all`):
#   neural-agent       trading loop + API on 127.0.0.1:3006
#   neural-dashboard   Next.js on 127.0.0.1:3005 (public read-only)
#
# 3000 stays free for other sites already on this VPS.
#
# Menu:
#   1  Fresh deploy — Node, .env, build, Nginx, Certbot, PM2 start
#   2  Update       — git pull, rebuild, pm2 restart (Nginx/SSL left as-is)
#
# Usage (on the VPS, from this repo):
#   bash deploy.sh                         # interactive menu
#   bash deploy.sh 1                       # fresh
#   bash deploy.sh 2                       # update
#   bash deploy.sh update --branch dashboard --reset
#
# Optional env:
#   DOMAIN=neuralalpha.io
#   WWW_DOMAIN=www.neuralalpha.io
#   CERTBOT_EMAIL=you@neuralalpha.io

APP_DIR="$(cd "$(dirname "$0")" && pwd)"
DOMAIN="${DOMAIN:-neuralalpha.io}"
WWW_DOMAIN="${WWW_DOMAIN:-www.${DOMAIN}}"
WEB_PORT="${WEB_PORT:-3005}"
AGENT_PORT="${AGENT_PORT:-3006}"
BRANCH="${BRANCH:-dashboard}"
MODE=""
RESET=0
SKIP_NGINX=0
SKIP_SSL=0
SKIP_GIT=0

OUR_APPS=(neural-agent neural-dashboard)
LEGACY_APPS=(neural-market-feed)

usage() {
  cat <<EOF
Neural Alpha — ${DOMAIN}

  bash deploy.sh              Interactive menu
  bash deploy.sh 1            Fresh deploy (Nginx, Certbot, PM2 start)
  bash deploy.sh 2            Update (git pull, rebuild, pm2 restart)
  bash deploy.sh fresh|update Same as 1 or 2

  --branch <name>   Branch to fetch (default: dashboard)
  --reset           Discard local code changes (keeps .env)
  --skip-nginx      Fresh deploy: do not install or reload Nginx
  --skip-ssl        Fresh deploy: do not request a Let's Encrypt certificate
  --skip-git        Do not fetch or pull
  -h, --help        Show this help

Domain defaults to neuralalpha.io (override with DOMAIN= / WWW_DOMAIN=).
Git always checks out origin/dashboard unless --branch is set.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    1|fresh) MODE=fresh; shift ;;
    2|update) MODE=update; shift ;;
    --branch) BRANCH="${2:-}"; shift 2 ;;
    --reset) RESET=1; shift ;;
    --skip-nginx) SKIP_NGINX=1; shift ;;
    --skip-ssl) SKIP_SSL=1; shift ;;
    --skip-git) SKIP_GIT=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage; exit 1 ;;
  esac
done

cd "$APP_DIR"

# ─── helpers ───────────────────────────────────────────────────
env_upsert() {
  node -e '
    const fs = require("fs");
    const file = ".env";
    const key = process.argv[1];
    const val = process.argv[2];
    let text = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (text && !text.endsWith("\n")) text += "\n";
    const re = new RegExp("^" + key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "=.*$", "m");
    if (re.test(text)) text = text.replace(re, key + "=" + val);
    else text += key + "=" + val + "\n";
    fs.writeFileSync(file, text);
  ' "$1" "$2"
}

env_get() {
  node -e '
    const fs = require("fs");
    const key = process.argv[1];
    if (!fs.existsSync(".env")) process.exit(0);
    for (const line of fs.readFileSync(".env", "utf8").split("\n")) {
      if (line.startsWith(key + "=")) {
        process.stdout.write(line.slice(key.length + 1));
        break;
      }
    }
  ' "$1"
}

ensure_cors() {
  node -e '
    const fs = require("fs");
    const extras = process.argv.slice(1);
    let text = fs.existsSync(".env") ? fs.readFileSync(".env", "utf8") : "";
    const match = text.match(/^CORS_ORIGINS=(.*)$/m);
    const current = match ? match[1].split(",").map((s) => s.trim()).filter(Boolean) : [];
    const merged = [...new Set([...current, ...extras])];
    const line = "CORS_ORIGINS=" + merged.join(",");
    if (match) text = text.replace(/^CORS_ORIGINS=.*$/m, line);
    else {
      if (text && !text.endsWith("\n")) text += "\n";
      text += line + "\n";
    }
    fs.writeFileSync(".env", text);
    process.stdout.write(merged.join(","));
  ' "$@"
}

pm2_names() {
  node -e '
    const { execSync } = require("child_process");
    let apps = [];
    try { apps = JSON.parse(execSync("pm2 jlist", { encoding: "utf8" }) || "[]"); }
    catch { process.exit(0); }
    for (const a of apps) if (a && a.name) console.log(a.name);
  '
}

pm2_has() {
  local name="$1"
  local existing
  existing="$(pm2_names || true)"
  grep -qx "$name" <<<"$existing"
}

run_root() {
  if [[ "$(id -u)" -eq 0 ]]; then
    "$@"
  else
    sudo "$@"
  fi
}

write_nginx() {
  local dest="$1"
  cat > "$dest" <<EOF
# Neural Alpha — ${DOMAIN}
# Generated by deploy.sh. Certbot may append the :443 server block.
# Upstream names are unique so this file can sit beside other sites.

upstream neuralalpha_dashboard {
    server 127.0.0.1:${WEB_PORT};
    keepalive 16;
}

upstream neuralalpha_agent_api {
    server 127.0.0.1:${AGENT_PORT};
    keepalive 8;
}

server {
    listen 80;
    listen [::]:80;
    server_name ${DOMAIN} ${WWW_DOMAIN};

    gzip on;
    gzip_vary on;
    gzip_proxied any;
    gzip_comp_level 5;
    gzip_min_length 256;
    gzip_types text/plain text/css application/json application/javascript application/xml image/svg+xml;

    location = /api/health {
        proxy_pass http://neuralalpha_agent_api;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }

    location = /api/agent/events {
        proxy_pass http://neuralalpha_dashboard;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_buffering off;
        proxy_read_timeout 86400s;
    }

    location = /api/agent/state {
        proxy_pass http://neuralalpha_dashboard;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 15s;
        proxy_buffering on;
    }

    location / {
        proxy_pass http://neuralalpha_dashboard;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF
}

choose_mode() {
  if [[ -n "$MODE" ]]; then
    return
  fi
  if [[ ! -t 0 ]]; then
    echo "No mode given. Use: bash deploy.sh 1   or   bash deploy.sh 2" >&2
    echo "" >&2
    usage >&2
    exit 1
  fi

  while true; do
    echo ""
    echo "╔══════════════════════════════════════════════════╗"
    echo "║   Neural Alpha — ${DOMAIN}"
    echo "╚══════════════════════════════════════════════════╝"
    echo ""
    echo "  1) Fresh deploy"
    echo "     Nginx + Certbot + build + PM2 start"
    echo ""
    echo "  2) Update"
    echo "     git pull origin/${BRANCH}, rebuild, pm2 restart"
    echo "     (keeps Nginx, SSL, and .env)"
    echo ""
    echo "  q) Quit"
    echo ""
    read -r -p "  Choose [1/2/q]: " choice
    case "$choice" in
      1) MODE=fresh; return ;;
      2) MODE=update; return ;;
      q|Q) echo "Cancelled."; exit 0 ;;
      *) echo "  Enter 1, 2, or q." ;;
    esac
  done
}

check_runtime() {
  local need_nginx="$1"
  echo ""
  echo "▸ Checking prerequisites..."

  for cmd in node npm pm2; do
    if ! command -v "$cmd" &>/dev/null; then
      echo "  ✗ $cmd not found."
      if [[ "$cmd" == "pm2" ]]; then
        echo "    → npm install -g pm2"
      fi
      exit 1
    fi
  done

  local node_ver
  node_ver="$(node -v | sed 's/v//' | cut -d. -f1)"
  if [[ "$node_ver" -lt 20 ]]; then
    echo "  ✗ Node.js 20+ required (found $(node -v))"
    exit 1
  fi

  if [[ "$need_nginx" -eq 1 && "$SKIP_NGINX" -eq 0 ]] && ! command -v nginx &>/dev/null; then
    echo "  ✗ nginx not found (or pass --skip-nginx)"
    exit 1
  fi
  if [[ "$need_nginx" -eq 1 && "$SKIP_SSL" -eq 0 ]] && ! command -v certbot &>/dev/null; then
    echo "  ⚠ certbot not found — skipping SSL (pass --skip-ssl to silence)"
    SKIP_SSL=1
  fi

  echo "  ✓ Node $(node -v) · npm $(npm -v) · pm2 $(pm2 -v | head -1)"
}

sync_git() {
  local required="$1"

  if [[ "$SKIP_GIT" -eq 1 ]]; then
    echo ""
    echo "▸ Git skipped (--skip-git)"
    return
  fi

  echo ""
  echo "▸ Syncing git (origin/${BRANCH})..."
  if [[ ! -d .git ]]; then
    echo "  ✗ $APP_DIR is not a git repo"
    echo "    Clone the dashboard branch into its own directory:"
    echo "    git clone -b dashboard --single-branch git@github-neural-alpha:ClipXonchain/neural-alpha.git ~/neural-alpha"
    exit 1
  fi

  local env_bak=""
  env_bak="$(mktemp /tmp/neural-alpha.env.XXXXXX)"
  if [[ -f .env ]]; then
    cp -a .env "$env_bak"
    echo "  ✓ .env backed up"
  else
    rm -f "$env_bak"
    env_bak=""
  fi

  git fetch origin

  if ! git rev-parse --verify "origin/$BRANCH" >/dev/null 2>&1; then
    echo "  ✗ origin/$BRANCH not found. Push the branch first, then re-run."
    [[ -n "$env_bak" ]] && rm -f "$env_bak"
    exit 1
  fi

  if [[ "$RESET" -eq 1 ]]; then
    git checkout -B "$BRANCH" "origin/$BRANCH"
    git reset --hard "origin/$BRANCH"
    echo "  ✓ Reset to origin/$BRANCH (code only)"
  else
    if [[ -n "$(git status --porcelain)" ]]; then
      echo "  ✗ Working tree is dirty. Re-run with --reset to discard local code"
      echo "    (your .env is preserved). Or commit/stash first."
      [[ -n "$env_bak" ]] && rm -f "$env_bak"
      exit 1
    fi
    git checkout -B "$BRANCH" "origin/$BRANCH"
    git pull --ff-only origin "$BRANCH"
    echo "  ✓ Pulled origin/$BRANCH"
  fi

  local head_sha origin_sha current_branch
  head_sha="$(git rev-parse HEAD)"
  origin_sha="$(git rev-parse "origin/$BRANCH")"
  current_branch="$(git rev-parse --abbrev-ref HEAD)"
  if [[ "$current_branch" != "$BRANCH" || "$head_sha" != "$origin_sha" ]]; then
    echo "  ✗ Not on origin/${BRANCH} (branch=${current_branch}, HEAD=${head_sha:0:12})"
    [[ -n "$env_bak" && -f "$env_bak" ]] && rm -f "$env_bak"
    exit 1
  fi
  echo "  ✓ Exact branch ${BRANCH} @ ${head_sha:0:12}"

  if [[ -n "$env_bak" && -f "$env_bak" ]]; then
    cp -a "$env_bak" .env
    rm -f "$env_bak"
    echo "  ✓ .env restored"
  fi
}

prepare_env() {
  echo ""
  echo "▸ Checking environment..."

  if [[ ! -f .env ]]; then
    if [[ -f .env.example ]]; then
      cp .env.example .env
      echo "  ⚠ Created .env from .env.example — set API_SECRET and wallet vars, then re-run"
      exit 1
    fi
    echo "  ✗ .env not found. Copy .env.example to .env and fill it in."
    exit 1
  fi

  env_upsert NODE_ENV production
  env_upsert READONLY true
  env_upsert NEXT_PUBLIC_READONLY true
  env_upsert PUBLIC_DASHBOARD_URL "https://${DOMAIN}"

  if [[ -z "$(env_get API_SECRET)" ]]; then
    local secret
    secret="$(openssl rand -hex 32)"
    env_upsert API_SECRET "$secret"
    echo "  ⚠ API_SECRET was empty — generated a new one"
    echo "    $secret"
  else
    echo "  ✓ API_SECRET already set (kept)"
  fi

  local cors_value
  cors_value="$(ensure_cors \
    "https://${DOMAIN}" \
    "https://${WWW_DOMAIN}" \
    "http://localhost:3000")"
  echo "  ✓ CORS_ORIGINS=${cors_value}"

  env_upsert DASHBOARD_PORT "$AGENT_PORT"
  env_upsert DASHBOARD_NEXT_PORT "$WEB_PORT"
  env_upsert AGENT_API_URL "http://127.0.0.1:${AGENT_PORT}"
  echo "  ✓ Ports: dashboard ${WEB_PORT}, agent API ${AGENT_PORT} (localhost only)"

  mkdir -p dashboard
  node -e '
    const fs = require("fs");
    const keys = [
      "NEXT_PUBLIC_READONLY",
      "READONLY",
      "API_SECRET",
      "AGENT_API_URL",
      "CORS_ORIGINS",
      "PUBLIC_DASHBOARD_URL",
    ];
    const src = fs.readFileSync(".env", "utf8");
    const map = {};
    for (const line of src.split("\n")) {
      const i = line.indexOf("=");
      if (i <= 0 || line.startsWith("#")) continue;
      map[line.slice(0, i)] = line.slice(i + 1);
    }
    const out = keys
      .filter((k) => map[k] != null && String(map[k]).trim() !== "")
      .map((k) => k + "=" + map[k])
      .join("\n") + "\n";
    fs.writeFileSync("dashboard/.env.local", out);
  '
  echo "  ✓ dashboard/.env.local synced"
  echo "  ✓ Public dashboard: READONLY=true · https://${DOMAIN}"
}

check_baw() {
  local mode
  mode="$(env_get AGENT_MODE)"
  if [[ "${mode}" != "live" ]]; then
    return
  fi
  echo ""
  echo "▸ Live mode — Binance Agentic Wallet..."
  if ! command -v baw &>/dev/null; then
    echo "  ⚠ baw CLI not on PATH. Install: npm i -g @binance/agentic-wallet"
    echo "    Then: bash deploy/baw-connect.sh"
  else
    echo "  ✓ baw: $(baw --version 2>/dev/null || echo found)"
    if baw wallet status --json >/dev/null 2>&1; then
      echo "  ✓ baw wallet status ok"
    else
      echo "  ⚠ baw not signed in. After deploy: bash deploy/baw-connect.sh"
    fi
  fi
}

install_deps() {
  echo ""
  echo "▸ Installing dependencies..."
  if [[ -f package-lock.json ]]; then
    npm ci
  else
    npm install
  fi
  echo "  ✓ Dependencies installed"
}

build_dashboard() {
  echo ""
  echo "▸ Building dashboard..."
  export NODE_ENV=production
  export NEXT_PUBLIC_READONLY=true
  export READONLY=true
  npm run dashboard:build
  mkdir -p logs neural-alpha/logs dashboard/logs
  echo "  ✓ Dashboard built (public read-only)"
}

install_nginx() {
  if [[ "$SKIP_NGINX" -eq 1 ]]; then
    return
  fi
  echo ""
  echo "▸ Nginx (${DOMAIN}, ${WWW_DOMAIN})..."
  local nginx_conf tmp_conf
  nginx_conf="/etc/nginx/sites-available/${DOMAIN}"
  tmp_conf="$(mktemp /tmp/neuralalpha.nginx.XXXXXX)"
  write_nginx "$tmp_conf"
  if [[ ! -f "$nginx_conf" ]]; then
    run_root cp "$tmp_conf" "$nginx_conf"
    run_root ln -sf "$nginx_conf" /etc/nginx/sites-enabled/
    echo "  ✓ Nginx site installed"
  else
    echo "  → Existing $nginx_conf left untouched (certbot SSL stays intact)"
  fi
  rm -f "$tmp_conf"
  run_root nginx -t
  run_root systemctl reload nginx
  echo "  ✓ Nginx reloaded"
}

install_ssl() {
  if [[ "$SKIP_SSL" -eq 1 ]]; then
    return
  fi
  echo ""
  echo "▸ SSL certificate..."
  if [[ ! -d "/etc/letsencrypt/live/${DOMAIN}" ]]; then
    local -a certbot
    certbot=(certbot --nginx -d "$DOMAIN" -d "$WWW_DOMAIN" --non-interactive --agree-tos --redirect)
    if [[ -n "${CERTBOT_EMAIL:-}" ]]; then
      certbot+=(--email "$CERTBOT_EMAIL")
    else
      certbot+=(--register-unsafely-without-email)
    fi
    echo "  → Requesting certificate for ${DOMAIN} and ${WWW_DOMAIN}..."
    run_root "${certbot[@]}"
    echo "  ✓ SSL certificate installed"
  else
    echo "  → Certificate already exists for ${DOMAIN}"
  fi
}

retire_legacy_pm2() {
  local existing name retire legacy
  existing="$(pm2_names || true)"
  while IFS= read -r name; do
    [[ -z "$name" ]] && continue
    retire=0
    for legacy in "${LEGACY_APPS[@]}"; do
      [[ "$name" == "$legacy" ]] && retire=1
    done
    if [[ "$name" =~ ^neural-agent-[0-9a-fA-F-]{8,} ]]; then
      retire=1
    fi
    if [[ "$retire" -eq 1 ]]; then
      echo "  → Retiring leftover process: $name"
      pm2 delete "$name" >/dev/null 2>&1 || true
    fi
  done <<< "$existing"
}

pm2_start_fresh() {
  echo ""
  echo "▸ Starting Neural Alpha via PM2..."
  retire_legacy_pm2
  local name
  for name in "${OUR_APPS[@]}"; do
    pm2 delete "$name" >/dev/null 2>&1 || true
  done
  pm2 start "$APP_DIR/ecosystem.config.cjs"
  pm2 save
  if [[ "$(id -u)" -eq 0 ]]; then
    pm2 startup systemd -u root --hp /root >/dev/null 2>&1 || true
    pm2 save >/dev/null
  fi
  echo "  ✓ neural-agent + neural-dashboard started"
  echo "  ✓ pm2 dump saved"
}

pm2_restart_update() {
  echo ""
  echo "▸ Restarting Neural Alpha via PM2..."
  retire_legacy_pm2
  if pm2_has neural-agent && pm2_has neural-dashboard; then
    pm2 restart neural-agent neural-dashboard --update-env
    echo "  ✓ neural-agent + neural-dashboard restarted"
  else
    echo "  → One or both apps were not running — starting them"
    pm2 start "$APP_DIR/ecosystem.config.cjs"
    echo "  ✓ neural-agent + neural-dashboard started"
  fi
  pm2 save
  echo "  ✓ pm2 dump saved"
}

health_check() {
  echo ""
  echo "▸ Health check..."
  sleep 3
  if curl -fsS --max-time 5 "http://127.0.0.1:${AGENT_PORT}/api/health" >/dev/null; then
    echo "  ✓ Agent API  http://127.0.0.1:${AGENT_PORT}/api/health"
  else
    echo "  ⚠ Agent API not up yet — check: pm2 logs neural-agent --lines 80"
  fi
  if curl -fsS --max-time 5 -o /dev/null "http://127.0.0.1:${WEB_PORT}/"; then
    echo "  ✓ Dashboard  http://127.0.0.1:${WEB_PORT}"
  else
    echo "  ⚠ Dashboard not up yet — check: pm2 logs neural-dashboard --lines 50"
  fi
}

print_done() {
  local title="$1"
  echo ""
  echo "╔══════════════════════════════════════════════════╗"
  echo "║   ✓ ${title}"
  echo "║                                                  ║"
  echo "║   Public (read-only):  https://${DOMAIN}"
  echo "║   WWW:                 https://${WWW_DOMAIN}"
  echo "║   Agent API (local):   http://127.0.0.1:${AGENT_PORT}/api ║"
  echo "║   Health:              https://${DOMAIN}/api/health"
  echo "║                                                  ║"
  echo "║   pm2 status                                     ║"
  echo "║   pm2 logs neural-agent --lines 80               ║"
  echo "║   pm2 restart neural-agent neural-dashboard      ║"
  echo "╚══════════════════════════════════════════════════╝"
  echo ""
  echo "Verify read-only:"
  echo "  curl -sS -X POST https://${DOMAIN}/api/agent/control/stop"
  echo "  → must return 401 Unauthorized"
  echo ""
}

fresh_deploy() {
  echo ""
  echo "▸ Mode: fresh deploy"
  check_runtime 1
  sync_git 0
  prepare_env
  check_baw
  install_deps
  build_dashboard
  install_nginx
  install_ssl
  pm2_start_fresh
  health_check
  echo "DNS must point ${DOMAIN} and ${WWW_DOMAIN} at this server before SSL."
  print_done "Fresh deploy complete"
}

update_deploy() {
  echo ""
  echo "▸ Mode: update (git pull, rebuild, pm2 restart)"
  check_runtime 0
  sync_git 1
  prepare_env
  install_deps
  build_dashboard
  pm2_restart_update
  health_check
  print_done "Update complete"
}

choose_mode

case "$MODE" in
  fresh) fresh_deploy ;;
  update) update_deploy ;;
  *) echo "Unknown mode: $MODE" >&2; exit 1 ;;
esac
